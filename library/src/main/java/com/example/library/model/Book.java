package com.example.library.model; //
import jakarta.persistence.*;

@Entity
@Table(name = "books")
public class Book{
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY) // this annotation specifies that the id field is the primary key and its value will be automatically generated by the database.
    private int id;
    @Column(nullable = false)
    private String title;
    @Column(nullable = false)
    private String author;

    @Column(name = "available_copies", nullable = false) // this annotation specifies that the availableCopies field will be mapped to a column named "available_copies" in the database.
    private int availableCopies;

    // Hibernate constructs entities through a no-argument constructor.
    protected Book() {}

    public Book(String title, String author, int availableCopies) {
        this(0, title, author, availableCopies);
    }

    public Book(int id, String title, String author){
        this(id, title, author, 0);
    }

    public Book(int id, String title, String author, int availableCopies){
        this.id = id;
        this.title = title;
        this.author = author;
        this.availableCopies = availableCopies;
    }

    public int getId() {
        return id;
    }

    public String getTitle() {
        return title;
    }

    public String getAuthor() {
        return author;
    }

    public int getAvailableCopies() {
        return availableCopies;
    }

    public void setTitle(String title) {
        this.title = title;
    }

    public void setAuthor(String author) {
        this.author = author;
    }
}
